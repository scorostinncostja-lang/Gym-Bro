def next_shot_text(done: int) -> str:
    """Подсказка после done принятых фото."""
    if done >= len(SHOTS):
        return "Все 4 кадра на месте."
    label = SHOTS[done][1]
    return f"Дальше ({done + 1}/{len(SHOTS)}): <b>{label}</b>. Присылай по одному или альбомом, по порядку."
