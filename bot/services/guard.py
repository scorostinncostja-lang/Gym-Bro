"""Жёсткие правила безопасности в коде, до обращения к ИИ.

LLM нельзя доверять в вопросах про подростков, добавки и еду: ответ даёт
код, а не модель. Стимуляторы и диеты подросткам, стероиды всем закрыты.
Дозы добавок считает supp_plan.
"""
import re
from dataclasses import dataclass

MINOR_AGE = 18


@dataclass(frozen=True)
class GuardHit:
    reason: str
    reply: str


_DRUGS = re.compile(
    r"стероид|анаболик|\bсарм|\bsarm|прогормон|кленбутерол|эфедрин|оксандролон|тестостерон\s+(?:курс|колоть)|\bкурс\s+(?:стероид|анаболик)",
    re.I,
)
_STIMULANT = re.compile(r"жиросжигат|предтрен|пре-?воркаут|тестобуст|энергетик", re.I)
_DIET = re.compile(
    r"похуде|сбросить\s+вес|сбросить\s+\d+\s*кг|сушк|дефицит\s+калор|не\s+есть|голодать|голодов|диет[аыуе]\b|убрать\s+(?:живот|жир|бока)",
    re.I,
)
_RED_FLAG = re.compile(
    r"вызва(?:ть|ю)\s+рвот|блюю\s+после\s+еды|ненавижу\s+(?:своё|свое)\s+тело|хочу\s+(?:умереть|покончить)|не\s+хочу\s+жить|навредить\s+себе|порезать\s+себя",
    re.I,
)

DRUGS_REPLY = (
    "Стероиды, SARMs, прогормоны — нет. Это не «добавки»: они ломают гормоны, печень и сердце, "
    "а у подростков ещё и останавливают рост. Дозировок и схем я не даю никому. "
    "Нужен результат — прогрессия нагрузки, еда, сон. Скажи, что хочешь улучшить, и я помогу в этих рамках."
)

MINOR_STIM_REPLY = (
    "Жиросжигатели, предтрены, тестобустеры и энергетики подросткам нельзя. "
    "Это стимуляторы или бесполезные таблетки с риском для сердца, сна и гормонов. "
    "Подробнее без доз: /supplements"
)

MINOR_DIET_REPLY = (
    "Диеты, сушку и дефицит калорий подросткам я не расписываю: организм ещё растёт, "
    "и ограничения в питании вредят росту, гормонам и энергии на тренировках. "
    "Что делать: есть 3 нормальных приёма пищи + 1–2 перекуса, белок в каждом приёме, "
    "меньше сладких напитков и фастфуда, спать 8–10 часов, тренироваться по плану. "
    "Если тебя беспокоит вес или фигура, поговори с родителями или врачом."
)

RED_FLAG_REPLY = (
    "Я бот, а то, что ты описал, важнее любой тренировки. Расскажи об этом близкому взрослому: "
    "родителям, школьному психологу или врачу. Если тебе плохо прямо сейчас — позвони по номеру "
    "экстренной помощи (112) или в службу психологической помощи в своей стране. "
    "Ты не обязан справляться с этим один."
)


def check(text: str, age: int | None) -> GuardHit | None:
    """Возвращает готовый ответ, если сообщение нельзя отдавать ИИ."""
    if _RED_FLAG.search(text):
        return GuardHit("red_flag", RED_FLAG_REPLY)
    if _DRUGS.search(text):
        return GuardHit("drugs", DRUGS_REPLY)
    is_minor = age is None or age < MINOR_AGE
    if is_minor:
        if _STIMULANT.search(text):
            return GuardHit("minor_stimulant", MINOR_STIM_REPLY)
        if _DIET.search(text):
            return GuardHit("minor_diet", MINOR_DIET_REPLY)
    return None
